#!/usr/bin/env python3
"""Build the machine-readable surface of die-zukunft.ch from the content sources.

Writes (all generated, committed, served by Cloudflare Pages as static files):
  static/llms.txt            curated navigational manifest (llmstxt.org)
  static/llms-full.txt       full corpus, English
  static/llms-full-de.txt    full corpus, German (the original language)
  static/md/<path>.md        Markdown twin of every DE page   -> die-zukunft.ch/md/<path>.md
  static/en/md/<path>.md     ... EN                           -> die-zukunft.ch/en/md/<path>.md
  static/fr/md/<path>.md     ... FR                           -> le-futur.ch/md/<path>.md (via lang-proxy worker)
  static/it/md/<path>.md     ... IT                           -> il-futuro.ch/md/<path>.md

Every HTML page links its twin with <link rel="alternate" type="text/markdown">.
Run before every build:  mise run build   (or: python3 scripts/build_llms.py)
Requires Python >= 3.11 (tomllib). No third-party packages.
"""
from __future__ import annotations

import datetime as dt
import re
import shutil
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "content"
STATIC = ROOT / "static"
LANGS = ["de", "fr", "it", "en"]
BASE = {"de": "https://die-zukunft.ch", "fr": "https://le-futur.ch", "it": "https://il-futuro.ch", "en": "https://die-zukunft.ch/en"}
BRAND = {"de": "Die Zukunft", "fr": "Le Futur", "it": "Il Futuro", "en": "The Future"}
LICENSE = "CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/)"
GENERATED = "<!-- Generated by scripts/build_llms.py from the site's content. Licence: CC BY 4.0. -->"


# ---------------------------------------------------------------- content model
def split_lang(name: str) -> tuple[str, str]:
    stem = name[:-3]
    for lang in ("fr", "it", "en"):
        if stem.endswith("." + lang):
            return stem[: -len(lang) - 1], lang
    return stem, "de"


class Page:
    def __init__(self, file: Path):
        self.file = file
        raw = file.read_text(encoding="utf-8")
        parts = raw.split("+++", 2)
        self.fm = tomllib.loads(parts[1]) if len(parts) == 3 else {}
        self.body = parts[2].strip() if len(parts) == 3 else ""
        self.extra = self.fm.get("extra", {})
        rel = file.relative_to(CONTENT)
        self.base, self.lang = split_lang(rel.name)
        self.dir = rel.parent.as_posix() if rel.parent.as_posix() != "." else ""
        self.is_section = self.base == "_index"
        self.key = (self.dir + "/" if self.dir else "") + self.base  # e.g. "aktuelles/neues-gesicht", "_index"
        slug = self.fm.get("slug", self.base)
        if self.is_section:
            self.path = self.dir  # "" for home
        else:
            self.path = (self.dir + "/" if self.dir else "") + slug
        self.title = self.fm.get("title", "")
        self.description = self.fm.get("description", "")
        self.date = self.fm.get("date")
        self.template = self.fm.get("template", "")

    @property
    def url(self) -> str:
        return BASE[self.lang] + "/" + (self.path + "/" if self.path else "")

    @property
    def twin_rel(self) -> str:
        return (self.path or "index") + ".md"

    @property
    def twin_url(self) -> str:
        return BASE[self.lang] + "/md/" + self.twin_rel


def load() -> dict[tuple[str, str], Page]:
    pages = {}
    for f in sorted(CONTENT.rglob("*.md")):
        if not f.read_text(encoding="utf-8").startswith("+++"):
            continue  # Zola ignores files without frontmatter
        p = Page(f)
        if p.fm.get("draft"):
            continue
        pages[(p.key, p.lang)] = p
    return pages


PAGES = load()


def url_for(target: str, lang: str) -> str:
    """Resolve a Zola internal link '@/vision.md' or '@/x/_index.md#anchor' for a language."""
    target, _, anchor = target.partition("#")
    key = target.removeprefix("@/").removesuffix(".md")
    page = PAGES.get((key, lang)) or PAGES.get((key, "de"))
    if not page:
        return target
    return page.url + ("#" + anchor if anchor else "")


def links(text: str, lang: str) -> str:
    return re.sub(r"\]\((@/[^)\s]+)\)", lambda m: "](" + url_for(m.group(1), lang) + ")", text)


def clean(text: str, lang: str) -> str:
    """Body/inline text -> plain Markdown: resolve @/ links, drop Zola shortcodes and HTML tags."""
    if not text:
        return ""
    text = links(str(text), lang)
    text = re.sub(r"\{\{.*?\}\}", "", text, flags=re.S)
    text = re.sub(r"\{%\s*(?:faq|callout)\([^)]*?(?:question=\"([^\"]*)\")?[^)]*\)\s*%\}", lambda m: f"**{m.group(1)}** " if m.group(1) else "", text)
    text = re.sub(r"\{%.*?%\}", "", text, flags=re.S)
    text = re.sub(r"<strong>(.*?)</strong>", r"**\1**", text)
    text = re.sub(r"<em>(.*?)</em>", r"*\1*", text)
    text = re.sub(r"<br\s*/?>", "\n", text)
    text = re.sub(r"</?[a-zA-Z][^>]*>", "", text)
    text = re.sub(r"\]\((/[^)]*)\)", lambda m: "](" + BASE["de"] + m.group(1) + ")", text)  # root-relative assets
    return re.sub(r"\n{3,}", "\n\n", text).strip()


def bullets(items, lang) -> str:
    return "\n".join("- " + clean(i, lang) for i in items) + "\n"


# ---------------------------------------------------------------- renderers
def render_sections(p: Page) -> str:
    out = []
    for s in p.extra.get("sections", []):
        out.append(f"## {clean(s.get('title', ''), p.lang)}\n")
        if s.get("text"):
            out.append(clean(s["text"], p.lang) + "\n")
        if s.get("points"):
            out.append(bullets(s["points"], p.lang))
        for it in s.get("items", []):
            out.append(f"- **{clean(it.get('label', ''), p.lang)}**: {clean(it.get('text', ''), p.lang)}")
        if s.get("items"):
            out.append("")
        for sub in s.get("subsections", []):
            out.append(f"### {clean(sub.get('title', ''), p.lang)}\n")
            if sub.get("text"):
                out.append(clean(sub["text"], p.lang) + "\n")
            if sub.get("points"):
                out.append(bullets(sub["points"], p.lang))
    return "\n".join(out)


def render_chapters(p: Page) -> str:
    out = []
    for c in p.extra.get("chapters", []):
        link = url_for(c["link"], p.lang) if c.get("link") else ""
        out.append(f"### [{clean(c['title'], p.lang)}]({link})\n\n{clean(c.get('text', ''), p.lang)}\n")
    return "\n".join(out)


def render_faq(p: Page) -> str:
    faq = p.extra.get("faq", [])
    if not faq:
        return ""
    out = [f"## {clean(p.extra.get('faq_title', 'FAQ'), p.lang)}\n"]
    for q in faq:
        out.append(f"**{clean(q['q'], p.lang)}**  \n{clean(q['a'], p.lang)}\n")
    return "\n".join(out)


def render_manifest(p: Page) -> str:
    x, L = p.extra, p.lang
    out = [f"Version {x.get('version')} · {x.get('version_date')}\n"]
    out.append(f"## {x.get('preamble_title')} ({x.get('preamble_hex')})\n\n{clean(x.get('preamble'), L)}\n")
    for i, t in enumerate(x.get("theses", []), 1):
        out.append(f"## {i:02d}. {clean(t['title'], L)} ({t['hex']})\n\n{clean(t['text'], L)}\n")
        if t.get("link"):
            out.append(f"→ [{clean(t.get('link_text', ''), L)}]({url_for(t['link'], L)})\n")
    out.append(f"## {x.get('commitments_title')} ({x.get('commitments_hex')})\n\n{clean(x.get('commitments_intro', ''), L)}\n")
    for i, c in enumerate(x.get("commitments", []), 1):
        out.append(f"{i}. **{clean(c['title'], L)}**: {clean(c['text'], L)}")
    out.append(f"\n## {x.get('not_title')} ({x.get('not_hex')})\n")
    out += [f"- **{clean(n['title'], L)}** {clean(n['text'], L)}" for n in x.get("not_points", [])]
    out.append(f"\n{clean(x.get('signature', ''), L)}\n")
    out.append("### Changelog\n")
    out += [f"- v{c['version']} ({c['date']}): {clean(c['note'], L)}" for c in x.get("changelog", [])]
    return "\n".join(out) + "\n"


def render_vision(p: Page) -> str:
    x, L = p.extra, p.lang
    out = [f"**{clean(x.get('lead'), L)}**\n"]
    out.append(f"## {x['shift_title']}\n\n{clean(x['shift_intro'], L)}\n")
    for s in x.get("shift", []):
        src = f" (Source: [{s['source']}]({s['source_url']}))" if s.get("source") else ""
        out.append(f"- **{s['figure']} · {clean(s['title'], L)}**: {clean(s['text'], L)}{src}")
    out.append(f"\n{clean(x.get('shift_note', ''), L)}\n")
    out.append(f"## {x['outcomes_title']}\n\n{clean(x['outcomes_intro'], L)}\n")
    out += [f"- **{clean(o['title'], L)}**: {clean(o['text'], L)}" for o in x.get("outcomes", [])]
    out.append(f"\n## {x['stack_title']}\n\n{clean(x['stack_intro'], L)}\n")
    for s in x.get("stack", []):
        link = f" → {url_for(s['link'], L)}" if s.get("link") else ""
        out.append(f"{s['layer']}. **{clean(s['title'], L)}**: {clean(s['text'], L)}{link}")
    out.append(f"\n## {x['sectors_title']}\n\n{clean(x['sectors_intro'], L)}\n")
    for s in x.get("sectors", []):
        out.append(f"### {s['label']}: {clean(s['title'], L)}\n\n{clean(s['text'], L)}\n")
        out.append(bullets(s.get("examples", []), L))
    out.append(f"## {x['guardrails_title']}\n\n{clean(x['guardrails_intro'], L)}\n")
    out += [f"- **{clean(g['title'], L)}** {clean(g['text'], L)}" for g in x.get("guardrails", [])]
    out.append(f"\n## {x['why_ch_title']}\n")
    out += [f"- **{clean(w['title'], L)}**: {clean(w['text'], L)}" for w in x.get("why_ch", [])]
    out.append(f"\n## {x['why_us_title']}\n")
    out += [clean(w, L) + "\n" for w in x.get("why_us", [])]
    out.append(f"## {x['targets_title']}\n\n{clean(x['targets_intro'], L)}\n")
    out += [f"- **{t['year']}**: {clean(t['goal'], L)}. {clean(t['how'], L)}" for t in x.get("targets", [])]
    out.append(f"\n## {x.get('sources_title', 'Sources')}\n")
    out += [f"- [{s['label']}]({s['url']})" for s in x.get("sources", [])]
    return "\n".join(out) + "\n"


def render_home(p: Page) -> str:
    x, L = p.extra, p.lang
    out = [f"**{BRAND[L]}. {x.get('hero_claim', '')}** {clean(x.get('hero_lead', ''), L)}\n"]
    out.append(bullets(x.get("hero_trio", []), L))
    if x.get("changes"):
        out.append(f"## {x['changes_title']}\n\n{clean(x.get('changes_intro', ''), L)}\n")
        out += [f"- **{clean(c['title'], L)}**: {clean(c['text'], L)}" for c in x["changes"]]
        out.append(f"\n{clean(x.get('changes_cta', ''), L)}\n")
    if x.get("pillars"):
        out.append(f"## {x['pillars_title']}\n\n{clean(x.get('pillars_intro', ''), L)}\n")
        out += [f"- [{clean(c['title'], L)}]({url_for(c['link'], L)}) ({c.get('hex', '')}): {clean(c['text'], L)}" for c in x["pillars"]]
    if x.get("timeline"):
        out.append(f"\n## {x['timeline_title']}\n\n{clean(x.get('horizon_intro', ''), L)}\n")
        out += [f"- **{t['phase']}: {t['title']}** ({t.get('area', '')}, {t.get('reach', '')}): {clean(t['text'], L)}" for t in x["timeline"]]
    if x.get("cta_title"):
        out.append(f"\n## {x['cta_title']}\n\n{clean(x.get('cta_text', ''), L)}\n")
    return "\n".join(out) + "\n"


def render_section_index(p: Page) -> str:
    children = sorted(
        (q for (k, l), q in PAGES.items() if l == p.lang and q.dir == p.dir and not q.is_section and p.dir),
        key=lambda q: str(q.date or ""), reverse=True)
    lines = [f"- [{q.title}]({q.url})" + (f" ({q.date})" if q.date else "") + (f": {q.description}" if q.description else "") for q in children]
    return ("\n".join(lines) + "\n") if lines else ""


def render(p: Page) -> str:
    head = [GENERATED, f"# {clean(p.title, p.lang)}\n"]
    if p.description:
        head.append(f"> {clean(p.description, p.lang)}\n")
    meta = [f"Source: {p.url}"]
    if p.date:
        meta.append(f"Published: {p.date}")
    meta.append(f"Publisher: {BRAND[p.lang]} (Swiss political party, Basel)")
    head.append(" · ".join(meta) + "\n")
    t = p.template
    if t == "manifest.html":
        body = render_manifest(p)
    elif t == "vision.html":
        body = render_vision(p)
    elif t == "index.html":
        body = render_home(p)
    else:
        body = "\n".join(filter(None, [render_sections(p), render_chapters(p), clean(p.body, p.lang), render_faq(p)]))
        if p.is_section and p.dir:
            body += "\n" + render_section_index(p)
    return "\n".join(head) + "\n" + body.strip() + "\n"


# ---------------------------------------------------------------- outputs
def write_twins() -> int:
    for lang in LANGS:
        d = STATIC / ("md" if lang == "de" else f"{lang}/md")
        if d.exists():
            shutil.rmtree(d)
    n = 0
    for p in PAGES.values():
        target = STATIC / ("md" if p.lang == "de" else f"{p.lang}/md") / p.twin_rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(render(p), encoding="utf-8")
        n += 1
    return n


ORDER = ["_index", "manifest", "vision", "programm", "souveraene-ki", "digitale-souveraenitaet", "robotik", "uebergaenge",
         "life-science", "grundeinkommen", "stadte-wohnen", "research-innovation", "energy-resilience", "offener-staat",
         "neutralitaet-frieden", "talent-integration", "sprache-verstaendigung", "kein-links-rechts", "abstimmungen",
         "menschen", "mitmachen"]


def corpus(lang: str) -> str:
    seen, parts = set(), []
    keys = [k for k in ORDER] + sorted(k for (k, l) in PAGES if l == lang and k.startswith("aktuelles/") and not k.endswith("_index")) \
        + sorted(k for (k, l) in PAGES if l in (lang, "de") and k.startswith("zukunftslabor/") and not k.endswith("_index"))
    for k in keys:
        p = PAGES.get((k, lang)) or (PAGES.get((k, "de")) if k.startswith("zukunftslabor/") else None)
        if p and k not in seen:
            seen.add(k)
            parts.append(render(p).replace(GENERATED + "\n", ""))
    intro = {
        "en": f"# The Future (Die Zukunft): full corpus, English\n\n> The complete programme, manifesto, vision and articles of The Future (Die Zukunft), a new Swiss political party based in Basel. German is the original language; see /llms-full-de.txt. Licence: {LICENSE}. Please cite as: The Future (Die Zukunft), <page title>, <URL>.\n",
        "de": f"# Die Zukunft: vollständiger Korpus, Deutsch\n\n> Programm, Manifest, Vision und Beiträge von Die Zukunft, einer neuen Schweizer Partei aus Basel. Deutsch ist die Originalsprache. Lizenz: {LICENSE}. Bitte zitieren als: Die Zukunft, <Seitentitel>, <URL>.\n",
    }[lang]
    return intro + f"\nGenerated {dt.date.today().isoformat()} from the site's content.\n\n---\n\n" + "\n---\n\n".join(parts)


